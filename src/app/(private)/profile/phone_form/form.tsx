import CountryDrawer from '@/src/components/CountryDrawer';
import Loading from '@/src/components/Loading';
import PhoneInput from '@/src/components/PhoneInput';
import SubmitButton from '@/src/components/SubmitButton';
import {Country} from '@/src/constants/types';
import {CONSTANT, COUNTRIES} from '@/src/constants/values';
import {useAuth} from '@/src/context/authContext';
import useAxiosPrivate from '@/src/hooks/useAxiosPrivate';
import {checkPhoneNumber, sendOTP} from '@/src/services/apiCalls';
import BottomSheet from '@gorhom/bottom-sheet/lib/typescript/components/bottomSheet/BottomSheet';
import {useRouter} from 'expo-router';
import React, {useEffect, useRef, useState} from 'react';
import {Alert, Keyboard, KeyboardAvoidingView, Platform, Pressable, Text, View} from 'react-native';
import {GestureHandlerRootView} from 'react-native-gesture-handler';
import {SafeAreaView} from 'react-native-safe-area-context';

const PhoneUpdateScreen = () => {
	const [country, setCountry] = useState<Country | null>(COUNTRIES[0]);
	const [sending, setSending] = useState(false);
	const [checking, setChecking] = useState(false);
	const [phone, setPhone] = useState('');
	const router = useRouter();
	const [isValide, setIsValide] = useState(false);
	const bottomSheetRef = useRef<BottomSheet>(null);
	const axiosPrivate = useAxiosPrivate();
	const {user} = useAuth();
	const [isKeyboardVisible, setIsKeyboardVisible] = useState(false);

	const handleSubmit = () => {
		if (phone === user?.phone) {
			return Alert.alert('Message', 'Please Enter your new phone number.');
		}
		setChecking((prev) => (prev = true));
		checkPhoneNumber(axiosPrivate, phone).then((checkRes) => {
			setChecking((prev) => (prev = false));
			if (!checkRes) return;
			if (checkRes.isPhoneExist) return Alert.alert('Message', 'This phone number alredy use by another account.');
			setSending((prev) => (prev = true));
			sendOTP(phone).then((res) => {
				setSending((prev) => (prev = false));
				if (!res) return;
				router.replace({
					pathname: '/(private)/profile/phone_form/verify_otp',
					params: {
						param: phone,
					},
				});
			});
		});
	};
	useEffect(() => {
		const showSubscription = Keyboard.addListener('keyboardDidShow', () => setIsKeyboardVisible(true));

		const hideSubscription = Keyboard.addListener('keyboardDidHide', () => setIsKeyboardVisible(false));

		return () => {
			showSubscription.remove();
			hideSubscription.remove();
		};
	}, []);

	return (
		<GestureHandlerRootView style={{flex: 1}}>
			<SafeAreaView edges={['bottom']} className="flex-1 bg-light-bgcolor-100 dark:bg-dark-bgcolor-100">
				<KeyboardAvoidingView
					style={{flex: 1}}
					behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
					keyboardVerticalOffset={Platform.OS === 'ios' ? 80 : 60}
				>
					{(checking || sending) && <Loading text={`${checking ? 'Cheking' : 'Sending'}`} />}
					<View className={`px-6 flex-1 justify-between ${isKeyboardVisible ? 'pb-10' : 'pb-3'}`}>
						<View className="items-center">
							<Text className="text-justify text-light-txtcolor-200">
								{CONSTANT.appName} will need to verify your phone number. Carrier charges may apply.{' '}
							</Text>
							<PhoneInput
								phone={phone}
								setPhone={setPhone}
								country={country}
								setIsValide={setIsValide}
								bottomSheetRef={bottomSheetRef}
							/>
							<Text className="text-justify text-light-txtcolor-200">
								You must insert sim card of above number to your phone to recieve otp, which generated by our
								system.
							</Text>
						</View>
						<SubmitButton text='Submit' disable={!isValide} onSubmit={handleSubmit} />
					</View>
					<CountryDrawer bottomSheetRef={bottomSheetRef} setCountry={setCountry} />
				</KeyboardAvoidingView>
			</SafeAreaView>
		</GestureHandlerRootView>
	);
};

export default PhoneUpdateScreen;
